    const s = D[K.lang][key] != null ? D[K.lang][key] : D['zh-CN'][key] != null ? D['zh-CN'][key] : key;
    return p ? s.replace(/\{(\w+)\}/g, (m, k) => (p[k] != null ? String(p[k]) : m)) : s;
